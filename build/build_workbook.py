def s_trace(wb):
    ws = wb.create_sheet("Traceability")
    headers = ["CPG 240 paragraph", "Chapter", "Guidance text", "Supports CPS 240",
               "Source attribution", "Verification note"]
    widths = [14, 30, 96, 18, 56, 56]
    sheet_frame(ws, "Guidance-to-requirement traceability",
                f"{STATUS} | Every numbered paragraph of the draft practice guide, and the "
                f"requirement it supports.",
                headers, widths, freeze_col="B")

    flat, _, _, _ = G.numbered()
    rows = []
    pending_src = None
    pending_ver = None
    # Attribution and verification lines follow the paragraph they qualify, so
    # walk backwards to attach them to the right row.
    items = [it for it in flat if it["k"] in ("p", "src", "ver")]
    for i, it in enumerate(items):
        if it["k"] != "p":
            continue
        src = ver = ""
        for j in range(i + 1, len(items)):
            if items[j]["k"] == "p":
                break
            if items[j]["k"] == "src" and not src:
                src = items[j]["t"]
            if items[j]["k"] == "ver" and not ver:
                ver = items[j]["t"]
        rows.append([it["n"], it["chapter"], it["t"],
                     ", ".join(it.get("req", [])) or "—", src, ver])
    write_rows(ws, rows, row_height=56)
    return ws


