def s_method(wb):
    ws = wb.create_sheet("Scoring Methodology")
    sheet_frame(ws, "Scoring methodology",
                f"{STATUS} | Weights and thresholds below are inputs. Change them and the "
                f"Gap Assessment recalculates.",
                ["Element", "Definition"], [30, 130])

    rows = [
        ["What is scored", "The CURRENT Australian prudential framework, as it stands before CPS "
         "240, in each model risk domain. Not entity maturity, and not a ranking of the comparator "
         "authorities against one another."],
        ["Against what", "The strongest comparator practice in that domain, identified by "
         "authority. Where no comparator addresses a domain at all — superannuation models — the "
         "benchmark is recorded as absent and the domain is assessed against the standard's own "
         "cross-industry objective instead."],
        ["Scale", "0 to 5 on each of four dimensions. The domain score is the unweighted mean of "
         "the four dimensions, so no single dimension can carry a domain."],
        ["Why four dimensions", "A domain can be addressed but vaguely, or precisely but only in "
         "guidance. Splitting coverage from specificity from enforceability prevents a general "
         "obligation in a binding standard from scoring as though it were a specific one."],
    ]
    write_rows(ws, rows)
    for r in range(FIRST_DATA_ROW, FIRST_DATA_ROW + len(rows)):
        ws.row_dimensions[r].height = 46

    r = FIRST_DATA_ROW + len(rows) + 1
    r = section_head(ws, r, "The four dimensions", span=2)
    dims = [[n, d] for n, d in SC.DIMENSIONS]
    write_rows(ws, dims, start=r)
    r += len(dims) + 1

    r = section_head(ws, r, "The 0–5 rubric", span=2)
    label(ws, f"A{r}", "Score", bold=True, fill=LIGHT)
    label(ws, f"B{r}", "Meaning", bold=True, fill=LIGHT)
    r += 1
    rub_start = r
    for score, name, desc in SC.RUBRIC:
        label(ws, f"A{r}", f"{score} — {name}", bold=True)
        label(ws, f"B{r}", desc)
        ws.row_dimensions[r].height = 30
        r += 1
    r += 1

    r = section_head(ws, r, "Derived measures", span=2)
    derived = [
        ["Domain score", "Mean of the four dimension scores for Australia. Column H of Gap "
         "Assessment."],
        ["Benchmark", "The strongest comparator score in that domain, with the authority named. "
         "Column I of Gap Assessment."],
        ["Gap", "MAX(0, Benchmark − Domain score). Negative gaps are floored at zero: where "
         "Australia already matches or exceeds the benchmark there is nothing to close."],
        ["Weighted gap", "Gap × domain weight. This is what drives the priority band."],
        ["Expected score after CPS 240", "Assessed position once the draft standard and guide are "
         "in force, on the same 0–5 scale. The difference from the current score is the value the "
         "instrument is expected to add."],
    ]
    write_rows(ws, derived, start=r)
    for i in range(len(derived)):
        ws.row_dimensions[r + i].height = 32
    r += len(derived) + 1

    r = section_head(ws, r, "Priority band thresholds — editable", span=2)
    label(ws, f"A{r}", "Band", bold=True, fill=LIGHT)
    label(ws, f"B{r}", "Weighted gap at or above", bold=True, fill=LIGHT)
    label(ws, f"C{r}", "Meaning", bold=True, fill=LIGHT)
    r += 1
    band_cells = {}
