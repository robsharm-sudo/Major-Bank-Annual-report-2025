def s_gap(wb, band_cells, weight_cells):
    ws = wb.create_sheet("Gap Assessment")
    headers = ["Domain", "Coverage", "Specificity", "Enforceability", "Alignment", "Weight",
               "Benchmark authority", "AU score now", "Benchmark", "Weighted gap", "Priority",
               "Expected after CPS 240", "Uplift", "CPS 240 requirements", "Source IDs"]
    widths = [34, 9, 10, 12, 10, 8, 20, 11, 11, 11, 11, 12, 9, 20, 26]
    sheet_frame(ws, "Gap assessment — current Australian framework against strongest comparator",
                f"{STATUS} | Scores 0–5 per the Scoring Methodology sheet. Every score cell carries "
                f"a comment giving the reasoning.",
                headers, widths, freeze_col="B")

    r = FIRST_DATA_ROW
    for d in SC.DOMAINS:
        wcell = weight_cells[d["domain"]]
        ws.cell(row=r, column=1, value=d["domain"])
        for i, v in enumerate(d["au"]):
            ws.cell(row=r, column=2 + i, value=v)
        ws.cell(row=r, column=6, value=f"={wcell}")
        ws.cell(row=r, column=7, value=d["bench_auth"])
        ws.cell(row=r, column=8, value=f"=ROUND(AVERAGE(B{r}:E{r}),2)")
        ws.cell(row=r, column=9, value=d["bench"])
        ws.cell(row=r, column=10, value=f"=ROUND(MAX(0,I{r}-H{r})*F{r},2)")
        ws.cell(row=r, column=11, value=(
            f'=IF(J{r}>={band_cells["Critical"]},"Critical",'
            f'IF(J{r}>={band_cells["High"]},"High",'
            f'IF(J{r}>={band_cells["Medium"]},"Medium","Low")))'
        ))
        ws.cell(row=r, column=12, value=d["post"])
        ws.cell(row=r, column=13, value=f"=ROUND(L{r}-H{r},2)")
        ws.cell(row=r, column=14, value=", ".join(d["reqs"]))
        ws.cell(row=r, column=15, value=", ".join(d["sources"]))

        note(ws, f"B{r}", f"{d['domain']}\n\nObserved gap:\n{d['gap']}")
        note(ws, f"L{r}", f"Expected position after CPS 240:\n\n{d['action']}")

        for c in range(1, 16):
            cell = ws.cell(row=r, column=c)
            cell.font = Font(name=ARIAL, size=9)
            cell.border = BORDER
            cell.alignment = Alignment(vertical="top", wrap_text=(c in (1, 7, 14, 15)))
            if (r - FIRST_DATA_ROW) % 2 == 1:
                cell.fill = PatternFill("solid", fgColor=ALT)
        for c in (2, 3, 4, 5, 6, 8, 9, 10, 12, 13):
            ws.cell(row=r, column=c).alignment = Alignment(horizontal="center", vertical="center")
        ws.row_dimensions[r].height = 30
        r += 1

    last = r - 1
    score_scale(ws, f"B{FIRST_DATA_ROW}:E{last}")
    score_scale(ws, f"H{FIRST_DATA_ROW}:I{last}")
    score_scale(ws, f"L{FIRST_DATA_ROW}:L{last}")
    gap_scale(ws, f"J{FIRST_DATA_ROW}:J{last}")
    priority_bands(ws, f"K{FIRST_DATA_ROW}:K{last}")

    r = last + 2
    label(ws, f"A{r}", "Totals", bold=True, size=10, colour=NAVY)
    ws.cell(row=r, column=8, value=f"=ROUND(AVERAGE(H{FIRST_DATA_ROW}:H{last}),2)")
    ws.cell(row=r, column=10, value=f"=ROUND(SUM(J{FIRST_DATA_ROW}:J{last}),2)")
    ws.cell(row=r, column=12, value=f"=ROUND(AVERAGE(L{FIRST_DATA_ROW}:L{last}),2)")
    ws.cell(row=r, column=13, value=f"=ROUND(L{r}-H{r},2)")
    for c in (8, 10, 12, 13):
        cell = ws.cell(row=r, column=c)
        cell.font = Font(name=ARIAL, size=9, bold=True, color=NAVY)
        cell.alignment = Alignment(horizontal="center")
    label(ws, f"N{r}", "Mean AU score, total weighted gap, mean expected score, mean uplift.",
          italic=True, colour=GREY)
    return ws, last


